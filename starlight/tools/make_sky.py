#!/usr/bin/env python3
"""Build the star catalogue and the constellation names the mod ships with.

    python3 tools/make_sky.py

Downloads the d3-celestial data (BSD-3-Clause, Olaf Frohn; positions and magnitudes from
Hipparcos, figures after the IAU/Sky & Telescope stick figures) and writes

    src/main/resources/assets/starlight/sky.txt    stars and figure lines
    src/main/resources/assets/starlight/lang/*.json   constellation names, English and German

Only what can rise above Kirchzarten (47.97 N) is kept: a star further south than
-(90 - 47.97) never clears the horizon there.
"""
import json
import math
import pathlib
import urllib.request

DATA = "https://cdn.jsdelivr.net/npm/d3-celestial@0.7.35/data/"
ROOT = pathlib.Path(__file__).resolve().parent.parent
ASSETS = ROOT / "src/main/resources/assets/starlight"

LATITUDE = 47.97
LOWEST_DEC = -(90 - LATITUDE)
# Background stars: bright enough to read as real sky, few enough that the figures dominate.
BACKGROUND_MAG = 5.0
POLARIS_HIP = 11767


def fetch(name):
    with urllib.request.urlopen(DATA + name) as response:
        return json.load(response)


def ra_of(lon):
    return lon % 360.0


def main():
    stars = fetch("stars.6.json")["features"]
    lines = fetch("constellations.lines.json")["features"]
    names = fetch("constellations.json")["features"]

    catalogue = {}  # (ra, dec) rounded -> (hip, ra, dec, mag)
    for f in stars:
        lon, lat = f["geometry"]["coordinates"]
        catalogue[(round(ra_of(lon), 3), round(lat, 3))] = (f["id"], ra_of(lon), lat, f["properties"]["mag"])

    def star_at(lon, lat):
        key = (round(ra_of(lon), 3), round(lat, 3))
        if key in catalogue:
            return catalogue[key]
        # A few figure vertices are rounded differently from the catalogue; take the closest.
        def dist(entry):
            _, ra, dec, _ = entry
            d_ra = (ra - ra_of(lon) + 180) % 360 - 180
            return (d_ra * math.cos(math.radians(lat))) ** 2 + (dec - lat) ** 2
        return min(catalogue.values(), key=dist)

    figure_index = {}  # hip -> index in output
    out_stars = []
    figures = []
    for f in lines:
        segments = []
        for strip in f["geometry"]["coordinates"]:
            ids = []
            for lon, lat in strip:
                hip, ra, dec, mag = star_at(lon, lat)
                if hip not in figure_index:
                    figure_index[hip] = len(out_stars)
                    out_stars.append((ra, dec, mag, 2 if hip == POLARIS_HIP else 1))
                ids.append(figure_index[hip])
            segments += [(a, b) for a, b in zip(ids, ids[1:])
                         if max(out_stars[a][1], out_stars[b][1]) > LOWEST_DEC]
        if segments:
            figures.append((f["id"], int(f["properties"]["rank"]), segments))

    # drop figure stars no kept segment uses, renumbering what is left
    used = sorted({i for _, _, segs in figures for seg in segs for i in seg})
    renumber = {old: new for new, old in enumerate(used)}
    out_stars = [out_stars[i] for i in used]
    figures = [(c, r, [(renumber[a], renumber[b]) for a, b in segs]) for c, r, segs in figures]
    if not any(s[3] == 2 for s in out_stars):
        raise SystemExit("Polaris is not in any figure")

    in_figure = set(figure_index)
    for f in stars:
        lon, lat = f["geometry"]["coordinates"]
        mag = f["properties"]["mag"]
        if f["id"] not in in_figure and mag <= BACKGROUND_MAG and lat > LOWEST_DEC:
            out_stars.append((ra_of(lon), lat, mag, 0))

    with open(ASSETS / "sky.txt", "w") as out:
        out.write("# Generated by tools/make_sky.py from d3-celestial (BSD-3-Clause), do not edit.\n")
        out.write("# S ra dec mag kind   (degrees; kind 0 background, 1 figure, 2 Polaris)\n")
        out.write("# C abbr rank a b a b ...   (figure lines as pairs of star indices)\n")
        for ra, dec, mag, kind in out_stars:
            out.write(f"S {ra:.4f} {dec:.4f} {mag:.2f} {kind}\n")
        for abbr, rank, segs in figures:
            out.write(f"C {abbr} {rank} " + " ".join(f"{a} {b}" for a, b in segs) + "\n")

    kept = {c for c, _, _ in figures}
    for lang, field in (("en_us", "name"), ("de_de", "de")):
        path = ASSETS / "lang" / f"{lang}.json"
        table = json.loads(path.read_text()) if path.exists() else {}
        table = {k: v for k, v in table.items() if not k.startswith("constellation.starlight.")}
        for f in names:
            if f["id"] in kept:
                table[f"constellation.starlight.{f['id']}"] = f["properties"][field] or f["properties"]["name"]
        path.write_text(json.dumps(table, ensure_ascii=False, indent=2) + "\n")

    print(f"{len(out_stars)} stars ({len(used)} in figures), {len(figures)} constellations")


if __name__ == "__main__":
    main()
